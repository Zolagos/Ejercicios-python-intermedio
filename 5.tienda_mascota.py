masco = input("Escriba el tipo de mascota que tiene: Perro, Gato, Conejo\n")
if masco == "Perro":
    print("Se le recomienda: Higado, salmon, arandanos, kefir natural.")
elif masco == "Gato":
    print("Se le recomienda: Carne seca, aceite de salmon, omega 3 y 6.")
elif masco == "Conejo":
    print("Se le recomienda: Zanahoria, lechuga, pepinos, calabacines.")
else:
    print("Tipo de mascota invalido")